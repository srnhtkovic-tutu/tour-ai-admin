-- 旅つづき スポット収集・抽出・評価・情報統合 再設計 Phase 1
-- 目的:
--   1. URLの取得順と施設名抽出順をDBに保持する
--   2. page_extractionから旧candidate_analysis工程を経由せずinformation_mergeへ進める
--   3. A/B/C対象ページがない施設名を統合対象外として保存できるようにする
--   4. 施設単位の失敗を記録し、ジョブ全体は後続施設の処理を継続できるようにする
--
-- 注意: このSQLは作業ブランチ用の未適用マイグレーション。
-- 本番Supabaseにはまだ適用していない。

-- 既存ジョブは旧処理経路を維持し、マイグレーション適用後の新規ジョブだけ新設計を使う。
alter table public.spot_import_jobs
  add column if not exists pipeline_version text;

update public.spot_import_jobs
set pipeline_version = 'legacy_v1'
where pipeline_version is null;

alter table public.spot_import_jobs
  alter column pipeline_version set default 'redesign_v1',
  alter column pipeline_version set not null;

comment on column public.spot_import_jobs.pipeline_version is
  'legacy_v1: 既存処理経路、redesign_v1: 2026-11-23設計の新規処理経路';

alter table public.spot_import_urls
  add column if not exists fetched_at timestamptz,
  add column if not exists fetched_order bigint generated by default as identity;

alter table public.spot_import_page_candidates
  add column if not exists extraction_order bigint generated by default as identity;

-- 既存データは取得完了時刻の代替として、現存するupdated_at/created_atを記録する。
-- 旧データの正確な取得順は過去の保存情報だけでは完全に復元できないため、
-- fetched_orderの初期値はDB上で再現可能な順序に固定する。
update public.spot_import_urls
set fetched_at = coalesce(updated_at, created_at)
where crawl_status = 'fetched'
  and fetched_at is null;

with ordered_urls as (
  select
    id,
    row_number() over (
      partition by job_id
      order by priority desc, created_at asc, id asc
    ) as sequence_no
  from public.spot_import_urls
  where crawl_status = 'fetched'
)
update public.spot_import_urls u
set fetched_order = ordered_urls.sequence_no
from ordered_urls
where u.id = ordered_urls.id;

create index if not exists idx_spot_import_urls_job_fetched_order
  on public.spot_import_urls (job_id, fetched_order);

create index if not exists idx_page_candidates_job_extraction_order
  on public.spot_import_page_candidates (job_id, extraction_order);

-- page_extractionは、実際に取得できたページの順序で処理する。
create or replace function private.claim_spot_import_url_batch(
  p_job_id uuid,
  p_execution_id uuid,
  p_lock_token uuid,
  p_stage text,
  p_limit integer
)
returns table(
  id uuid,
  url text,
  page_title text,
  link_label text,
  crawl_depth integer,
  priority integer,
  extracted_text text
)
language plpgsql
security definer
set search_path to ''
as $function$
begin
  perform private.assert_spot_import_execution(
    p_job_id, p_execution_id, p_lock_token, p_stage
  );

  if p_limit is null or p_limit < 1 or p_limit > 200 then
    raise exception 'invalid_batch_limit';
  end if;

  if p_stage = 'url_collection' then
    return query
    with picked as (
      select u.id
      from public.spot_import_urls u
      where u.job_id = p_job_id
        and (
          u.crawl_status = 'pending'
          or (u.crawl_status = 'failed' and u.retry_count < 2)
        )
      order by u.priority desc, u.created_at asc, u.id asc
      limit p_limit
      for update skip locked
    )
    update public.spot_import_urls u
    set crawl_status = 'processing',
        processing_execution_id = p_execution_id,
        updated_at = now()
    from picked
    where u.id = picked.id
    returning u.id, u.url, u.page_title, u.link_label,
              u.crawl_depth, u.priority, u.extracted_text;

  elsif p_stage = 'page_extraction' then
    return query
    with picked as (
      select u.id
      from public.spot_import_urls u
      where u.job_id = p_job_id
        and u.crawl_status = 'fetched'
        and u.candidate_extraction_status = 'pending'
        and u.processing_execution_id is null
      order by u.fetched_order asc nulls last, u.created_at asc, u.id asc
      limit p_limit
      for update skip locked
    )
    update public.spot_import_urls u
    set candidate_extraction_status = 'processing',
        processing_execution_id = p_execution_id,
        updated_at = now()
    from picked
    where u.id = picked.id
    returning u.id, u.url, u.page_title, u.link_label,
              u.crawl_depth, u.priority, u.extracted_text;

  elsif p_stage = 'candidate_analysis' then
    -- 旧ジョブの途中再開との互換性のため、既存工程は残す。
    -- 新規ジョブはDispatcherからこの工程へ遷移しない。
    return query
    with picked as (
      select u.id
      from public.spot_import_urls u
      where u.job_id = p_job_id
        and u.candidate_extraction_status = 'completed'
        and u.analysis_status = 'pending'
        and u.processing_execution_id is null
      order by u.priority desc, u.created_at asc, u.id asc
      limit p_limit
      for update skip locked
    )
    update public.spot_import_urls u
    set analysis_status = 'processing',
        processing_execution_id = p_execution_id,
        updated_at = now()
    from picked
    where u.id = picked.id
    returning u.id, u.url, u.page_title, u.link_label,
              u.crawl_depth, u.priority, u.extracted_text;
  else
    raise exception 'unsupported_stage_for_url_claim';
  end if;
end;
$function$;

-- 取得成功時点で取得順を確定する。
create or replace function private.commit_spot_import_crawl_page_v2(
  p_job_id uuid,
  p_execution_id uuid,
  p_lock_token uuid,
  p_url_id uuid,
  p_result_status text,
  p_page_title text default null,
  p_extracted_text text default null,
  p_error text default null,
  p_discovered_urls jsonb default '[]'::jsonb
)
returns jsonb
language plpgsql
security definer
set search_path to ''
as $function$
declare
  v_region_id uuid;
  v_allowed_domains text[];
  v_source_url text;
  v_item jsonb;
  v_url text;
  v_host text;
  v_added integer := 0;
begin
  perform private.assert_spot_import_execution(
    p_job_id, p_execution_id, p_lock_token, 'url_collection'
  );

  if p_result_status not in ('fetched', 'failed', 'skipped') then
    raise exception 'invalid_crawl_result_status';
  end if;

  if p_result_status = 'fetched' then
    if jsonb_typeof(coalesce(p_discovered_urls, '[]'::jsonb)) <> 'array'
       or jsonb_array_length(coalesce(p_discovered_urls, '[]'::jsonb)) > 500 then
      raise exception 'invalid_discovered_urls_payload';
    end if;
    if length(coalesce(p_extracted_text, '')) > 12000 then
      raise exception 'extracted_text_too_long';
    end if;
  end if;

  select r.id, r.allowed_domains, u.url
    into v_region_id, v_allowed_domains, v_source_url
  from public.spot_import_jobs j
  join public.regions r on r.id = j.region_id
  join public.spot_import_urls u on u.job_id = j.id
  where j.id = p_job_id
    and u.id = p_url_id
    and u.processing_execution_id = p_execution_id
    and u.crawl_status = 'processing'
    and r.is_active = true
  for update of u;

  if not found then
    raise exception 'url_not_claimed_by_execution';
  end if;

  if p_result_status = 'fetched' then
    update public.spot_import_urls
    set page_title = left(nullif(p_page_title, ''), 300),
        extracted_text = p_extracted_text,
        crawl_status = 'fetched',
        crawl_error = null,
        fetched_at = now(),
        fetched_order = pg_catalog.nextval(
          pg_catalog.pg_get_serial_sequence(
            'public.spot_import_urls',
            'fetched_order'
          )::regclass
        ),
        processing_execution_id = null,
        updated_at = now()
    where id = p_url_id and job_id = p_job_id;

    for v_item in
      select value from jsonb_array_elements(coalesce(p_discovered_urls, '[]'::jsonb))
    loop
      v_url := btrim(coalesce(v_item->>'url', ''));

      if v_url !~* '^https://[^/:?#]+(:[0-9]+)?([/?#]|$)' then
        raise exception 'invalid_discovered_url';
      end if;

      v_host := lower((regexp_match(v_url, '^https://([^/:?#]+)'))[1]);

      if not exists (
        select 1
        from unnest(v_allowed_domains) d(domain)
        where lower(d.domain) = v_host
      ) then
        raise exception 'discovered_url_domain_not_allowed';
      end if;

      insert into public.spot_import_urls (
        job_id, url, page_title, link_label, discovered_from_url,
        crawl_depth, priority, crawl_status
      )
      values (
        p_job_id,
        v_url,
        nullif(v_item->>'page_title',''),
        nullif(v_item->>'link_label',''),
        v_source_url,
        greatest(0, coalesce((v_item->>'crawl_depth')::integer, 0)),
        coalesce((v_item->>'priority')::integer, 0),
        'pending'
      )
      on conflict (job_id, url) do nothing;

      if found then
        v_added := v_added + 1;
      end if;
    end loop;

  elsif p_result_status = 'skipped' then
    update public.spot_import_urls
    set crawl_status = 'skipped',
        analysis_status = 'skipped',
        crawl_error = left(coalesce(p_error, 'skipped'), 2000),
        processing_execution_id = null,
        updated_at = now()
    where id = p_url_id and job_id = p_job_id;

  else
    update public.spot_import_urls
    set crawl_status = 'failed',
        crawl_error = left(coalesce(p_error, 'crawl_failed'), 2000),
        retry_count = retry_count + 1,
        processing_execution_id = null,
        updated_at = now()
    where id = p_url_id and job_id = p_job_id;
  end if;

  return jsonb_build_object(
    'result_status', p_result_status,
    'discovered_urls_added', v_added
  );
end;
$function$;

-- 統合対象外と施設単位エラーを既存テーブル内で管理する。
create or replace function private.save_spot_import_merge_progress_v2(
  p_job_id uuid,
  p_execution_id uuid,
  p_lock_token uuid,
  p_spot_name text,
  p_status text,
  p_source_count integer,
  p_input_char_count integer,
  p_source_candidate_ids uuid[],
  p_source_url_ids uuid[],
  p_sources jsonb,
  p_merged_data jsonb,
  p_model text,
  p_relevance_status text,
  p_relevance_results jsonb,
  p_relevance_model text,
  p_relevance_progress jsonb
)
returns uuid
language plpgsql
security definer
set search_path to ''
as $function$
declare
  v_region_id uuid;
  v_id uuid;
  v_error_message text;
begin
  perform private.assert_spot_import_execution(
    p_job_id, p_execution_id, p_lock_token, 'information_merge'
  );

  if nullif(btrim(p_spot_name), '') is null then
    raise exception 'spot_name_required';
  end if;

  if p_status not in ('pending','completed','failed','skipped') then
    raise exception 'invalid_merge_status';
  end if;

  if p_source_count is not null and p_source_count < 0 then
    raise exception 'invalid_source_count';
  end if;

  if p_input_char_count is not null and p_input_char_count < 0 then
    raise exception 'invalid_input_char_count';
  end if;

  if p_relevance_status is not null
     and p_relevance_status not in ('pending','in_progress','completed','failed','skipped') then
    raise exception 'invalid_relevance_status';
  end if;

  select j.region_id
    into v_region_id
  from public.spot_import_jobs j
  join public.regions r on r.id = j.region_id
  where j.id = p_job_id and r.is_active = true;

  if v_region_id is null then
    raise exception 'active_job_region_required';
  end if;

  if p_status = 'failed' or p_relevance_status = 'failed' then
    v_error_message := left(
      coalesce(
        nullif(p_relevance_progress->>'last_error', ''),
        nullif(p_relevance_progress->>'merge_error', ''),
        '処理に失敗しました。'
      ),
      2000
    );
  else
    v_error_message := null;
  end if;

  insert into public.spot_import_merged_v2 (
    job_id, spot_name, status, source_count, input_char_count,
    source_candidate_ids, source_url_ids, sources, merged_data, model,
    relevance_status, relevance_results, relevance_model,
    relevance_progress, region_id, error_message
  )
  values (
    p_job_id, btrim(p_spot_name), p_status,
    coalesce(p_source_count, 0), coalesce(p_input_char_count, 0),
    coalesce(p_source_candidate_ids, '{}'::uuid[]),
    coalesce(p_source_url_ids, '{}'::uuid[]),
    coalesce(p_sources, '[]'::jsonb),
    p_merged_data, p_model, p_relevance_status,
    p_relevance_results, p_relevance_model, p_relevance_progress,
    v_region_id, v_error_message
  )
  on conflict (job_id, spot_name)
  do update set
    status = excluded.status,
    source_count = excluded.source_count,
    input_char_count = excluded.input_char_count,
    source_candidate_ids = excluded.source_candidate_ids,
    source_url_ids = excluded.source_url_ids,
    sources = excluded.sources,
    merged_data = coalesce(excluded.merged_data, public.spot_import_merged_v2.merged_data),
    model = coalesce(excluded.model, public.spot_import_merged_v2.model),
    error_message = excluded.error_message,
    relevance_status = coalesce(excluded.relevance_status, public.spot_import_merged_v2.relevance_status),
    relevance_results = coalesce(excluded.relevance_results, public.spot_import_merged_v2.relevance_results),
    relevance_model = coalesce(excluded.relevance_model, public.spot_import_merged_v2.relevance_model),
    relevance_progress = coalesce(excluded.relevance_progress, public.spot_import_merged_v2.relevance_progress),
    region_id = excluded.region_id,
    updated_at = now()
  returning id into v_id;

  return v_id;
end;
$function$;

-- 施設単位の失敗が残った場合、ジョブ全体は一部エラーとして完了させる。
create or replace function public.finish_spot_import_execution(
  p_job_id uuid,
  p_execution_id uuid,
  p_lock_token uuid,
  p_next_stage text default null
)
returns jsonb
language plpgsql
security definer
set search_path to ''
as $function$
declare
  v_control private.spot_import_system_control%rowtype;
  v_job public.spot_import_jobs%rowtype;
  v_new_status text;
  v_new_stage text;
  v_outcome text;
  v_has_facility_errors boolean := false;
begin
  if auth.role() <> 'service_role' then
    raise exception 'not_authorized';
  end if;

  select * into v_control
  from private.spot_import_system_control
  where id = 1
  for update;

  if v_control.lock_status <> 'active'
     or v_control.locked_job_id <> p_job_id
     or v_control.execution_id <> p_execution_id
     or v_control.lock_token <> p_lock_token
     or v_control.lock_expires_at <= now() then
    raise exception 'execution_lock_mismatch_or_expired';
  end if;

  select * into v_job
  from public.spot_import_jobs
  where id = p_job_id
  for update;
  if not found then
    raise exception 'job_not_found';
  end if;

  if p_next_stage is not null and p_next_stage not in
    ('url_collection','page_extraction','candidate_analysis','information_merge') then
    raise exception 'invalid_next_stage';
  end if;

  if v_job.requested_action = 'pause' then
    v_new_status := 'paused';
    v_new_stage := v_job.current_stage;
    v_outcome := null;
  elsif v_job.requested_action = 'cancel' then
    v_new_status := 'cancelled';
    v_new_stage := v_job.current_stage;
    v_outcome := 'cancelled';
  elsif not v_control.system_enabled then
    v_new_status := 'pending';
    v_new_stage := v_job.current_stage;
    v_outcome := null;
  elsif p_next_stage is null then
    select exists (
      select 1
      from public.spot_import_merged_v2 m
      where m.job_id = p_job_id
        and (m.status = 'failed' or m.relevance_status = 'failed')
    ) into v_has_facility_errors;

    v_new_status := 'completed';
    v_new_stage := 'human_review';
    v_outcome := case when v_has_facility_errors then 'partial_error' else 'normal_completed' end;
  else
    v_new_status := 'running';
    v_new_stage := p_next_stage;
    v_outcome := null;
  end if;

  update public.spot_import_jobs
  set status = v_new_status,
      current_stage = v_new_stage,
      final_outcome = v_outcome,
      requested_action = null,
      requested_at = null,
      requested_by = null,
      updated_at = now()
  where id = p_job_id;

  perform private.write_spot_import_execution_log(
    'worker_completed',
    p_job_id,
    p_execution_id,
    v_job.region_id,
    v_job.current_stage,
    '処理単位を終了',
    jsonb_build_object('result_status', v_new_status, 'next_stage', v_new_stage, 'final_outcome', v_outcome)
  );

  update private.spot_import_system_control
  set lock_status = 'unlocked',
      locked_job_id = null,
      execution_id = null,
      lock_token = null,
      lock_acquired_at = null,
      last_heartbeat_at = null,
      lock_expires_at = null,
      anomaly_reason = null,
      updated_at = now()
  where id = 1;

  return jsonb_build_object(
    'status', v_new_status,
    'current_stage', v_new_stage,
    'final_outcome', v_outcome
  );
end;
$function$;


-- Dispatcherがジョブごとの処理バージョンを選択できるようにする。
create or replace function public.claim_spot_import_execution(
  p_lease_seconds integer
)
returns jsonb
language plpgsql
security definer
set search_path to ''
as $function$
declare
  v_control private.spot_import_system_control%rowtype;
  v_job public.spot_import_jobs%rowtype;
  v_execution_id uuid;
  v_lock_token uuid;
begin
  if auth.role() <> 'service_role' then
    raise exception 'not_authorized';
  end if;
  if p_lease_seconds is null or p_lease_seconds <= 0 then
    raise exception 'invalid_lease_seconds';
  end if;

  select * into v_control
  from private.spot_import_system_control
  where id = 1
  for update;

  if not found or not v_control.system_enabled then
    return null;
  end if;

  if v_control.lock_status = 'anomaly' then
    return null;
  end if;

  if v_control.lock_status = 'active' then
    if v_control.lock_expires_at > now() then
      return null;
    end if;

    update private.spot_import_system_control
    set lock_status = 'anomaly',
        anomaly_reason = 'lease_expired',
        updated_at = now()
    where id = 1;

    perform private.write_spot_import_execution_log(
      'anomaly_detected',
      v_control.locked_job_id,
      v_control.execution_id,
      null,
      null,
      '実行リース期限切れを検出。ロックを保持して異常停止',
      jsonb_build_object('reason', 'lease_expired')
    );
    return jsonb_build_object('status', 'anomaly');
  end if;

  select j.* into v_job
  from public.spot_import_jobs j
  join public.regions r on r.id = j.region_id
  where j.status in ('pending', 'running')
    and j.current_stage is not null
    and j.current_stage <> 'human_review'
    and (j.requested_action is null or j.requested_action = 'start')
    and r.is_active = true
  order by j.queue_entered_at asc nulls last, j.id asc
  limit 1
  for update of j skip locked;

  if not found then
    return null;
  end if;

  v_execution_id := gen_random_uuid();
  v_lock_token := gen_random_uuid();

  update private.spot_import_system_control
  set lock_status = 'active',
      locked_job_id = v_job.id,
      execution_id = v_execution_id,
      lock_token = v_lock_token,
      lock_acquired_at = now(),
      last_heartbeat_at = now(),
      lock_expires_at = now() + make_interval(secs => p_lease_seconds),
      anomaly_reason = null,
      updated_at = now()
  where id = 1;

  update public.spot_import_jobs
  set status = 'running',
      requested_action = null,
      requested_at = null,
      requested_by = null,
      updated_at = now()
  where id = v_job.id;

  perform private.write_spot_import_execution_log(
    'execution_claimed',
    v_job.id,
    v_execution_id,
    v_job.region_id,
    v_job.current_stage,
    '実行権を取得',
    jsonb_build_object('pipeline_version', v_job.pipeline_version)
  );

  return jsonb_build_object(
    'job_id', v_job.id,
    'stage', v_job.current_stage,
    'pipeline_version', v_job.pipeline_version,
    'execution_id', v_execution_id,
    'lock_token', v_lock_token,
    'lease_expires_at', now() + make_interval(secs => p_lease_seconds)
  );
end;
$function$;
